import { Employee } from '@domain/entities/employee.entity';
import { DomainConflictError } from '@domain/errors/domain.errors';
import { Address } from '@domain/value-objects/address.vo';
import { BirthDate } from '@domain/value-objects/birth-date.vo';
import { ContractDate } from '@domain/value-objects/contract-date.vo';
import { DataSource, QueryFailedError } from 'typeorm';
import { PostgresEmployeeRepository } from '@infrastructure/persistence/postgres-employee.repository';
import { EmployeeOrmEntity } from '@infrastructure/persistence/postgres/employee.orm-entity';
import { EmployeeQueryDto } from '@shared/dtos/employee/employee-query.dto';

describe('PostgresEmployeeRepository', () => {
  const employee = Employee.create(
    'Example Employee',
    'employee@example.com',
    new BirthDate(`${new Date().getFullYear() - 30}-01-01`),
    new ContractDate('2020-01-01'),
    'Engineer',
    new Address('Main Street', 'Example City', 'Example Country', '12345'),
  );

  it('maps the employee email unique constraint to a domain conflict', async () => {
    const driverError = Object.assign(new Error('duplicate key'), {
      code: '23505',
      constraint: 'UQ_employees_email',
      table: 'employees',
    });
    const databaseError = new QueryFailedError('INSERT INTO employees', [], driverError);
    const dataSource = {
      transaction: jest.fn().mockRejectedValue(databaseError),
    } as unknown as DataSource;
    const repository = new PostgresEmployeeRepository(dataSource);

    await expect(repository.save(employee)).rejects.toBeInstanceOf(DomainConflictError);
  });

  it('recognizes existing autogenerated PostgreSQL email constraints', async () => {
    const driverError = Object.assign(new Error('duplicate key'), {
      code: '23505',
      detail: 'Key (email)=(employee@example.com) already exists.',
      constraint: 'UQ_765bc1ac8967533a04c74a9f6af',
      table: 'employees',
    });
    const databaseError = new QueryFailedError('INSERT INTO employees', [], driverError);
    const dataSource = {
      transaction: jest.fn().mockRejectedValue(databaseError),
    } as unknown as DataSource;
    const repository = new PostgresEmployeeRepository(dataSource);

    await expect(repository.save(employee)).rejects.toBeInstanceOf(DomainConflictError);
  });

  it('returns a mapped page of employees with pagination metadata', async () => {
    const record = Object.assign(new EmployeeOrmEntity(), {
      id: 'a06a98d5-0c66-49f8-a525-7f8ac25612f8',
      name: 'Page Employee',
      email: 'page.employee@example.com',
      birthDate: `${new Date().getFullYear() - 30}-01-01`,
      contractDate: '2020-01-01',
      profession: 'Engineer',
      addressStreet: 'Main Street',
      addressCity: 'Example City',
      addressCountry: 'Example Country',
      addressZipCode: '12345',
      compensations: [],
    });
    const employeeRepository = {
      findAndCount: jest.fn().mockResolvedValue([[record], 21]),
    };
    const dataSource = {
      getRepository: jest.fn().mockReturnValue(employeeRepository),
    } as unknown as DataSource;
    const repository = new PostgresEmployeeRepository(dataSource);
    const query = Object.assign(new EmployeeQueryDto(), { pageNumber: 2, pageSize: 10 });

    const result = await repository.find(query);

    expect(employeeRepository.findAndCount).toHaveBeenCalledWith({
      order: { id: 'ASC' },
      skip: 10,
      take: 10,
    });
    expect(result).toMatchObject({
      pageNumber: 2,
      pageSize: 10,
      totalPages: 3,
      totalRecords: 21,
    });
    expect(result.items).toHaveLength(1);
    expect(result.items[0].getName()).toBe('Page Employee');
  });
});
